/**
 * Compile MJML email templates into build manifest (Node build phase only)
 * @module core/build/phases/03-compile/email-templates
 */

const fs = require('fs');
const path = require('path');
const { sha256 } = require('../../graph/hash');
const { BUNDLED_AUTH_TEMPLATES } = require('../../../../plugins/email/bundled-templates');

/**
 * @typedef {Object} EmailTemplateChunk
 * @property {string} id
 * @property {string} [mjml]
 * @property {string} [html]
 * @property {'bundled'|'project'|'config'} kind
 * @property {string} hash
 * @property {string} [source]
 */

/**
 * @param {import('../../index').BuildContextInternal} ctx
 * @returns {{ emailTemplates: Record<string, EmailTemplateChunk> }}
 */
function compileEmailTemplates(ctx) {
  /** @type {Record<string, EmailTemplateChunk>} */
  const emailTemplates = {};

  for (const [id, source] of Object.entries(BUNDLED_AUTH_TEMPLATES)) {
    const mjml = source.mjml || '';
    emailTemplates[id] = {
      id,
      mjml,
      kind: 'bundled',
      hash: sha256(mjml),
      source: `webspresso:plugins/email/bundled-templates#${id}`,
    };
  }

  const emailDir = path.resolve(ctx.cwd, ctx.config.emailDir || 'emails');
  if (fs.existsSync(emailDir) && fs.statSync(emailDir).isDirectory()) {
    for (const file of fs.readdirSync(emailDir)) {
      if (!file.endsWith('.mjml')) continue;
      const id = path.basename(file, '.mjml');
      const absPath = path.join(emailDir, file);
      const mjml = fs.readFileSync(absPath, 'utf8');
      emailTemplates[id] = {
        id,
        mjml,
        kind: 'project',
        hash: sha256(mjml),
        source: path.relative(ctx.cwd, absPath),
      };
    }
  }

  for (const [id, chunk] of Object.entries(emailTemplates)) {
    ctx.graph.addNode(`email:${id}`, 'email-template', chunk.hash);
  }

  return { emailTemplates };
}

/**
 * Emit ESM module with embedded email templates (Workers-safe)
 * @param {Record<string, EmailTemplateChunk>} emailTemplates
 * @returns {string}
 */
function buildEmailTemplatesMjs(emailTemplates = {}) {
  const payload = JSON.stringify(emailTemplates, null, 2);
  return `/** Auto-generated by webspresso build — do not edit */
export const emailTemplates = ${payload};
export default emailTemplates;
`;
}

/**
 * Convert manifest emailTemplates to emailPlugin `templates` option
 * @param {object} manifest
 * @returns {{ templates: Record<string, { mjml?: string, html?: string }> }}
 */
function emailPluginOptionsFromManifest(manifest) {
  const chunks = manifest?.emailTemplates || {};
  /** @type {Record<string, { mjml?: string, html?: string }>} */
  const templates = {};

  for (const [id, chunk] of Object.entries(chunks)) {
    if (chunk?.mjml) templates[id] = { mjml: chunk.mjml };
    else if (chunk?.html) templates[id] = { html: chunk.html };
  }

  return { templates };
}

module.exports = {
  compileEmailTemplates,
  buildEmailTemplatesMjs,
  emailPluginOptionsFromManifest,
};
