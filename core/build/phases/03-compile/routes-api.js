/**
 * Compile API routes — handlers barrel + schema precompile
 * @module core/build/phases/03-compile/routes-api
 */

const path = require('path');
const fs = require('fs');
const { compileSchema } = require('../../../compileSchema');
const { zodToJsonSchema } = require('zod-to-json-schema');

/**
 * @param {object} route
 * @param {number} index
 */
function handlerKey(route, index) {
  return `r${index}_handler`;
}

/**
 * @param {object} route
 * @param {string} outputDir
 */
function importPath(route, outputDir) {
  const rel = path.relative(outputDir, route.absPath).split(path.sep).join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

/**
 * Serialize compiled zod schema to JSON-safe object
 * @param {object|null} compiled
 */
function schemaToJson(compiled) {
  if (!compiled) return { query: null, body: null, params: null };
  const out = {};
  for (const key of ['query', 'body', 'params']) {
    if (compiled[key]) {
      try {
        out[key] = zodToJsonSchema(compiled[key], { target: 'openApi3' });
      } catch {
        out[key] = null;
      }
    } else {
      out[key] = null;
    }
  }
  return out;
}

/**
 * @param {import('../../index').BuildContextInternal} ctx
 * @param {object[]} apiRoutes
 */
function compileApiRoutes(ctx, apiRoutes, outputDir) {
  const lines = ['/** Generated by webspresso build — do not edit */'];
  const exports = [];
  /** @type {Record<string, unknown>} */
  const schemas = {};

  apiRoutes.forEach((route) => {
    const key = handlerKey(route, route.registrationIndex);
    const modVar = `m${route.registrationIndex}`;
    const relImport = importPath(route, outputDir);
    lines.push(`import * as ${modVar} from '${relImport}';`);

    let hasSchema = false;
    if (fs.existsSync(route.absPath)) {
      try {
        const mod = require(route.absPath);
        const fn = typeof mod === 'function' ? mod : mod.default || mod.handler;
        if (typeof fn === 'function') {
          const compiled = compileSchema(route.absPath, mod);
          schemas[key] = { compiled: true, jsonSchema: schemaToJson(compiled) };
          hasSchema = typeof mod.schema === 'function';
        }
      } catch (err) {
        schemas[key] = { compiled: false, error: err.message };
      }
    }

    lines.push(`export const ${key} = typeof ${modVar}.default === 'function' ? ${modVar}.default : (${modVar}.handler || ${modVar}.default);`);
    if (hasSchema) {
      lines.push(`export const ${key}_schema = ${modVar}.schema;`);
    }
    exports.push({ key, hasSchema });
  });

  lines.push('');
  lines.push('export const handlers = {');
  for (const { key, hasSchema } of exports) {
    lines.push(`  ${key},`);
    if (hasSchema) {
      lines.push(`  ${key}_schema,`);
    }
  }
  lines.push('};');

  return {
    handlersSource: lines.join('\n'),
    schemas,
  };
}

module.exports = { compileApiRoutes, handlerKey, schemaToJson };
